// sync-disposable-list.mjs — maintenance script for the community list.
// downloads the cc0 disposable-email-domains blocklist and writes it as a
// generated, committed module so the core keeps working offline and stays
// free of runtime network access. rerun periodically; note the snapshot date.
// usage: npm run sync:lists

import { writeFile, mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outPath = join(here, "..", "src", "generated", "disposable-domains.ts");

const SOURCE_URL =
  "https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf";

const res = await fetch(SOURCE_URL);
if (!res.ok) {
  console.error(`failed to fetch list: http ${res.status}`);
  process.exit(1);
}
const text = await res.text();
const domains = [
  ...new Set(
    text
      .split(/\r?\n/)
      .map((l) => l.trim().toLowerCase())
      .filter((l) => l.length > 0 && !l.startsWith("#"))
  ),
].sort();

const today = new Date().toISOString().slice(0, 10);
const header = `// generated by scripts/sync-disposable-list.mjs — do not edit by hand.
// source: disposable-email-domains/disposable-email-domains (github)
// license: cc0 1.0 (public domain dedication)
// snapshot date: ${today}
// entries are a community blocklist; not verified per-domain here

export const COMMUNITY_LIST_SNAPSHOT = "${today}";

export const COMMUNITY_DISPOSABLE_DOMAINS: string[] = [
${domains.map((d) => `  "${d}",`).join("\n")}
];
`;

await mkdir(dirname(outPath), { recursive: true });
await writeFile(outPath, header);
console.log(`wrote ${domains.length} domains to src/generated/disposable-domains.ts (snapshot ${today})`);
